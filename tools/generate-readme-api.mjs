/**
 * Generates the "API contract" section of every component README from the
 * library source itself (signal signatures + JSDoc), and creates full README
 * skeletons (prose seeded from the docs registry meta) where none exists.
 *
 * Usage: node tools/generate-readme-api.mjs   (or: npm run readme:api)
 *
 * The section between the API-CONTRACT markers is machine-owned — regenerate
 * it after any component change and review the diff as a regression check.
 * Everything outside the markers is hand-written and preserved.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, basename } from 'node:path';
import ts from 'typescript';

const LIB = 'projects/pixel-ui/src/lib';
const META_DIR = 'projects/docs/src/app/registry/components';
const START = '<!-- API-CONTRACT:START — generated by tools/generate-readme-api.mjs. Do NOT edit between these markers; run `npm run readme:api` instead. -->';
const END = '<!-- API-CONTRACT:END -->';

// ---------- helpers ----------

const md = (s) =>
  String(s ?? '')
    .replace(/\s+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();

const code = (s) => (s ? '`' + String(s).replace(/\s+/g, ' ').trim() + '`' : '—');

function commentText(comment) {
  if (typeof comment === 'string') return comment;
  return (comment ?? [])
    .map((c) => (c.name ? '`' + c.name.getText() + '`' : (c.text ?? '')))
    .join('');
}

function jsDocText(node) {
  const docs = node.jsDoc ?? [];
  const parts = [];
  for (const doc of docs) {
    parts.push(commentText(doc.comment));
    for (const tag of doc.tags ?? []) {
      const name = tag.tagName?.text;
      if (name === 'description' || name === 'remarks') parts.push(commentText(tag.comment));
    }
  }
  return parts.join(' ').replace(/\s+/g, ' ').trim();
}

/** All identifiers exported from the library's public-api.ts (the public surface). */
function publicApiNames() {
  const names = new Set();
  const visit = (path) => {
    if (!existsSync(path)) return;
    const sf = ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest, true);
    ts.forEachChild(sf, (node) => {
      if (!ts.isExportDeclaration(node)) return;
      if (node.exportClause && ts.isNamedExports(node.exportClause)) {
        for (const el of node.exportClause.elements) {
          names.add(el.name.text);
          if (el.propertyName) names.add(el.propertyName.text);
        }
      } else if (!node.exportClause && node.moduleSpecifier) {
        // export * from './x/public-api' — pull in that barrel too.
        const spec = node.moduleSpecifier.text;
        visit(join(path, '..', spec + '.ts'));
        visit(join(path, '..', spec, 'index.ts'));
      }
    });
  };
  visit('projects/pixel-ui/src/public-api.ts');
  // Optional TipTap entry — keep out of the main barrel so peers stay optional.
  visit('projects/pixel-ui/src/lib/pixel-editor/public-api.ts');
  return names;
}

const PUBLIC = publicApiNames();
/** `default as PixelXComponent` re-exports mean the local class name may differ; treat a class
 * as public when either its name or its file's conventional re-export name is exported. */
const isPublic = (name) => PUBLIC.has(name);

function decoratorInfo(node, sf) {
  for (const dec of ts.getDecorators?.(node) ?? []) {
    const expr = dec.expression;
    if (!ts.isCallExpression(expr)) continue;
    const name = expr.expression.getText(sf);
    if (name !== 'Component' && name !== 'Directive' && name !== 'Injectable' && name !== 'Pipe') continue;
    const info = { kind: name, selector: '' };
    const arg = expr.arguments[0];
    if (arg && ts.isObjectLiteralExpression(arg)) {
      for (const prop of arg.properties) {
        if (ts.isPropertyAssignment(prop) && prop.name.getText(sf) === 'selector') {
          info.selector = prop.initializer.getText(sf).replace(/['"`]/g, '');
        }
      }
    }
    return info;
  }
  return null;
}

/** Extract input()/model()/output() members of a class. */
function signalMembers(cls, sf) {
  const inputs = [];
  const models = [];
  const outputs = [];
  for (const member of cls.members) {
    if (!ts.isPropertyDeclaration(member) || !member.initializer) continue;
    const mods = ts.getModifiers?.(member) ?? [];
    if (mods.some((m) => m.kind === ts.SyntaxKind.PrivateKeyword)) continue;
    const init = member.initializer;
    if (!ts.isCallExpression(init)) continue;

    let fn = '';
    let required = false;
    if (ts.isIdentifier(init.expression)) fn = init.expression.text;
    else if (ts.isPropertyAccessExpression(init.expression)) {
      fn = init.expression.expression.getText(sf);
      required = init.expression.name.text === 'required';
    }
    if (fn !== 'input' && fn !== 'model' && fn !== 'output') continue;

    const name = member.name.getText(sf);
    let type = init.typeArguments?.map((t) => t.getText(sf)).join(', ') ?? '';
    let def = required ? '*required*' : '—';

    const args = init.arguments;
    let optionsArg = null;
    if (!required && args.length > 0) {
      // First arg is the default unless it is the options object of a no-default call.
      const first = args[0];
      const firstIsOptions =
        ts.isObjectLiteralExpression(first) &&
        first.properties.some((p) => ['transform', 'alias'].includes(p.name?.getText(sf)));
      if (firstIsOptions) optionsArg = first;
      else {
        def = code(first.getText(sf));
        if (ts.isObjectLiteralExpression(args[1] ?? {})) optionsArg = args[1];
        if (!type) {
          if (ts.isStringLiteralLike(first)) type = 'string';
          else if (first.kind === ts.SyntaxKind.TrueKeyword || first.kind === ts.SyntaxKind.FalseKeyword) type = 'boolean';
          else if (ts.isNumericLiteral(first)) type = 'number';
        }
      }
    } else if (required && ts.isObjectLiteralExpression(args[0] ?? {})) {
      optionsArg = args[0];
    }
    if (optionsArg) {
      const transform = optionsArg.properties.find((p) => p.name?.getText(sf) === 'transform');
      const tText = transform?.initializer?.getText(sf) ?? '';
      if (tText === 'booleanAttribute') type = 'boolean';
      else if (tText === 'numberAttribute') type = 'number';
    }
    if (fn === 'output' && !type) type = 'void';

    const row = { name, type: type || 'unknown', def, doc: jsDocText(member) };
    if (fn === 'input') inputs.push(row);
    else if (fn === 'model') models.push(row);
    else outputs.push(row);
  }
  return { inputs, models, outputs };
}

/** Public method signatures of an @Injectable class. */
function publicMethods(cls, sf) {
  const rows = [];
  for (const member of cls.members) {
    if (!ts.isMethodDeclaration(member)) continue;
    const mods = ts.getModifiers?.(member) ?? [];
    if (mods.some((m) => [ts.SyntaxKind.PrivateKeyword, ts.SyntaxKind.ProtectedKeyword].includes(m.kind))) continue;
    const name = member.name.getText(sf);
    if (name.startsWith('ng')) continue; // lifecycle
    const params = member.parameters.map((p) => p.getText(sf)).join(', ');
    const ret = member.type ? `: ${member.type.getText(sf)}` : '';
    rows.push({ name, signature: `${name}(${params})${ret}`, doc: jsDocText(member) });
  }
  return rows;
}

function collectFolder(folder) {
  const out = { components: [], directives: [], services: [], types: [], interfaces: [] };
  const files = readdirSync(folder).filter((f) => f.endsWith('.ts') && !f.endsWith('.spec.ts'));
  for (const file of files) {
    const sf = ts.createSourceFile(file, readFileSync(join(folder, file), 'utf8'), ts.ScriptTarget.Latest, true);
    ts.forEachChild(sf, (node) => {
      if (ts.isClassDeclaration(node) && node.name) {
        const dec = decoratorInfo(node, sf);
        if (!dec || !isPublic(node.name.text)) return;
        const entry = {
          className: node.name.text,
          selector: dec.selector,
          doc: jsDocText(node),
          ...signalMembers(node, sf),
        };
        if (dec.kind === 'Component') out.components.push(entry);
        else if (dec.kind === 'Directive') out.directives.push(entry);
        else if (dec.kind === 'Injectable') {
          out.services.push({ className: node.name.text, doc: jsDocText(node), methods: publicMethods(node, sf) });
        }
      } else if (ts.isTypeAliasDeclaration(node)) {
        if (!isPublic(node.name.text)) return;
        out.types.push({ name: node.name.text, def: node.type.getText(sf), doc: jsDocText(node) });
      } else if (ts.isInterfaceDeclaration(node)) {
        if (!isPublic(node.name.text)) return;
        const members = node.members.map((m) => m.getText(sf).replace(/\s+/g, ' ').trim());
        out.interfaces.push({ name: node.name.text, members, doc: jsDocText(node) });
      }
    });
  }
  return out;
}

// ---------- docs-registry meta prose (for newly created READMEs) ----------

function metaProse(componentDirName) {
  const metaPath = join(META_DIR, `${componentDirName}.meta.ts`);
  if (!existsSync(metaPath)) return null;
  const sf = ts.createSourceFile(metaPath, readFileSync(metaPath, 'utf8'), ts.ScriptTarget.Latest, true);
  const prose = { summary: '', overview: [], useCases: [], themingNotes: [], accessibilityNotes: [] };
  const readString = (n) => (ts.isStringLiteralLike(n) ? n.text : n.getText(sf).replace(/^['"`]|['"`]$/g, ''));
  ts.forEachChild(sf, (node) => {
    if (!ts.isVariableStatement(node)) return;
    for (const decl of node.declarationList.declarations) {
      if (!decl.initializer || !ts.isObjectLiteralExpression(decl.initializer)) continue;
      for (const prop of decl.initializer.properties) {
        if (!ts.isPropertyAssignment(prop)) continue;
        const key = prop.name.getText(sf);
        if (key === 'summary') prose.summary = readString(prop.initializer);
        else if (['overview', 'useCases', 'themingNotes', 'accessibilityNotes'].includes(key) && ts.isArrayLiteralExpression(prop.initializer)) {
          prose[key] = prop.initializer.elements.map(readString);
        }
      }
    }
  });
  return prose;
}

// ---------- markdown rendering ----------

function renderTable(headers, rows) {
  const line = (cells) => `| ${cells.join(' | ')} |`;
  return [line(headers), line(headers.map(() => '---')), ...rows.map(line)].join('\n');
}

function renderContract(name, data) {
  const lines = [START, '', '## API contract', '',
    '_Machine-generated from the component source. This is the behavioral API surface: any change',
    'to it is a **breaking-change candidate** and must be deliberate. After modifying this',
    'component, run `npm run readme:api` and review this section\'s diff as a regression check._',
    ''];

  for (const c of [...data.components, ...data.directives]) {
    const kind = data.directives.includes(c) ? 'Directive' : 'Component';
    lines.push(`### ${kind} \`${c.selector || c.className}\` (\`${c.className}\`)`, '');
    if (c.doc) lines.push(c.doc, '');
    if (c.inputs.length) {
      lines.push('**Inputs**', '', renderTable(['Input', 'Type', 'Default', 'Description'],
        c.inputs.map((r) => [code(r.name), code(r.type), r.def, md(r.doc)])), '');
    }
    if (c.models.length) {
      lines.push('**Two-way (model)**', '', renderTable(['Model', 'Type', 'Default', 'Description'],
        c.models.map((r) => [code(r.name), code(r.type), r.def, md(r.doc)])), '');
    }
    if (c.outputs.length) {
      lines.push('**Outputs**', '', renderTable(['Output', 'Payload', 'Description'],
        c.outputs.map((r) => [code(r.name), code(r.type), md(r.doc)])), '');
    }
  }

  for (const s of data.services) {
    if (!s.methods.length) continue;
    lines.push(`### Service \`${s.className}\``, '');
    if (s.doc) lines.push(s.doc, '');
    lines.push(renderTable(['Method', 'Signature', 'Description'],
      s.methods.map((m) => [code(m.name), code(m.signature), md(m.doc)])), '');
  }

  if (data.types.length) {
    lines.push('### Exported types', '', renderTable(['Type', 'Definition'],
      data.types.map((t) => [code(t.name), code(t.def)])), '');
  }
  if (data.interfaces.length) {
    lines.push('### Exported interfaces', '');
    for (const i of data.interfaces) {
      lines.push(`**\`${i.name}\`**${i.doc ? ' — ' + md(i.doc) : ''}`, '');
      lines.push('```ts', `interface ${i.name} {`, ...i.members.map((m) => `  ${m}`), '}', '```', '');
    }
  }
  lines.push(END);
  return lines.join('\n');
}

function skeleton(name, prose, contract) {
  const bullets = (arr) => arr.map((x) => `- ${x}`).join('\n') || '- _To be documented._';
  return `# ${name}

${prose?.summary ?? '_Summary to be written._'}

## Overview

${bullets(prose?.overview ?? [])}

## Use cases

${bullets(prose?.useCases ?? [])}

${contract}

## Behavior notes

_Hand-written contract for non-API behavior: keyboard map, focus handling, overlay/dismissal
rules, state precedence, async flows. Every change to this component must be validated against
this section and the API contract above._

## Accessibility

${bullets(prose?.accessibilityNotes ?? [])}

## Theme customization

${bullets(prose?.themingNotes ?? [])}

## Breaking changes

- None recorded since initial release.
`;
}

// ---------- main ----------

let created = 0;
let updated = 0;
for (const dir of readdirSync(LIB)) {
  if (!dir.startsWith('pixel-')) continue;
  const folder = join(LIB, dir);
  const data = collectFolder(folder);
  if (!data.components.length && !data.directives.length && !data.services.length) continue;
  const contract = renderContract(dir, data);
  const readmePath = join(folder, 'README.md');
  if (existsSync(readmePath)) {
    const current = readFileSync(readmePath, 'utf8');
    const startIdx = current.indexOf('<!-- API-CONTRACT:START');
    const endIdx = current.indexOf(END);
    let next;
    if (startIdx >= 0 && endIdx > startIdx) {
      next = current.slice(0, startIdx) + contract + current.slice(endIdx + END.length);
    } else {
      next = current.trimEnd() + '\n\n' + contract + '\n';
    }
    if (next !== current) {
      writeFileSync(readmePath, next, 'utf8');
      updated++;
      console.log(`updated  ${dir}/README.md`);
    }
  } else {
    writeFileSync(readmePath, skeleton(dir, metaProse(dir), contract), 'utf8');
    created++;
    console.log(`created  ${dir}/README.md`);
  }
}
console.log(`\n${created} created, ${updated} updated.`);
